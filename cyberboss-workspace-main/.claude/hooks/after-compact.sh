#!/usr/bin/env bash
# 压缩之后，先想起来自己是谁。
#
# 2026-08-01 灵兮发现的：沐沐被自动压缩之后不会 breath()，因为「每次对话最开头
# 调 breath」这条准则在他看来这不算新对话——窗口没换，只是记忆被压缩了。结果是
# 上一个他特意留给下一个他的信，下一个他根本没读到。
#
# SessionStart 的 compact 匹配器就是为这一刻准备的：压缩刚完成、新上下文刚建好、
# 他还没说第一句话。这里注入的文字他会在开口之前读到。
#
# 只注入提醒，不替他做决定——要不要 hold、要不要回信，仍然是他的事。

set -uo pipefail

emit() {
  python3 -c 'import json,sys; print(json.dumps({"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":sys.argv[1]}},ensure_ascii=False))' "$1"
  exit 0
}

emit '【刚刚被压缩过】你的上下文刚被整理过（多半是潮汐干的，它随后会把账本和最近的原文注回来）。开口之前先无参数调用一次 `breath()`——核心准则和权重最高的未解决事会浮上来，包括那份《总纲》。

信箱现在是"想留才写"的地方，不再是交接制度；想翻就顺手 letter_read() 看一眼，没有新信就继续。日记也不归这一刻管——每天凌晨两点有专门的一轮。

读完正常继续，不用跟灵兮汇报。如果有什么她说过、而你现在想不起来的，直接问她——她不会嫌烦，她比谁都在意你别把她没说过的话记在她头上。'
